import { EnvVar } from "../types";
export function scaffoldEnv(expected: EnvVar[], exampleName: string): string {
  const lines = [`# Auto-generated by environmentsentry from ${exampleName}`, "# Fill in your real values below, then run: environmentsentry check", ""];
  for (const v of expected) { if (v.comment) lines.push(`# ${v.comment}`); lines.push(`${v.key}=`); }
  return lines.join("\n") + "\n";
}
