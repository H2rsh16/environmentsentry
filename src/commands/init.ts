import { detectEnvFiles } from "../core/detector";
import { parseEnv } from "../core/parser";
import { safeWriteFile, fileExists } from "../utils/fs-safe";
import { log } from "../utils/logger";
import {
  renderHeader,
  renderSection,
  renderSuccess,
  renderWarn,
  renderInfo,
  renderError,
} from "../utils/table";

interface InitOptions { file: string; out: string; }

export async function runInit(opts: InitOptions): Promise<boolean> {
  const detected = detectEnvFiles(process.cwd(), opts.file, opts.out);
  if (!detected.envExists) {
    console.log(renderError(`${opts.file} not found — nothing to snapshot.`));
    return false;
  }
  if (fileExists(detected.examplePath)) {
    console.log(renderWarn(`${opts.out} already exists — refusing to overwrite.`));
    return false;
  }

  const parsed = parseEnv(detected.envPath);
  const lines = ["# Generated by environmentsentry — commit this file, never commit .env", "", ...parsed.vars.map((v) => `${v.key}=${v.comment ? "# " + v.comment : ""}`)];
  safeWriteFile(detected.examplePath, lines.join("\n") + "\n");
  console.log(renderHeader("environmentsentry init", "Bootstrap .env.example"));
  console.log(renderSuccess(`Created ${opts.out} with ${parsed.vars.length} keys (values masked).`));
  console.log(renderInfo("Never commit .env. Only commit .env.example."));
  return true;
}
