import * as fs from "fs";
import * as path from "path";
import pc from "picocolors";
import { detectEnvFiles } from "../core/detector";
import { parseEnv } from "../core/parser";
import { scanUsageDir } from "./usage";
import { safeWriteFile } from "../utils/fs-safe";
import { renderTable, renderHeader, renderSection, renderSuccess, renderWarn, renderInfo } from "../utils/table";
import { log } from "../utils/logger";

interface ExampleOptions { root: string; out: string; include?: string; exclude?: string; }

export async function runExample(opts: ExampleOptions): Promise<{ ok: boolean }> {
  const root = path.resolve(opts.root);
  const outPath = path.resolve(root, opts.out);
  const { used } = scanUsageDir(root, 10, opts.include, opts.exclude);
  const detected = detectEnvFiles(root, ".env", ".env.example");
  const existingExample = detected.exampleExists ? parseEnv(detected.examplePath).vars : [];
  const existingKeys = new Set(existingExample.map((v) => v.key));
  const usedKeys = new Set(used.keys());
  const lines: string[] = [];
  lines.push("# Generated by environmentsentrry from source-code usage");
  lines.push("# Do not commit real values. Fill in values before deploying.");
  lines.push("");
  const added: string[] = [];
  const rows: Array<Record<string, string>> = [];
  for (const key of usedKeys) {
    if (existingKeys.has(key)) continue;
    const refs = used.get(key);
    if (refs && refs.length > 0) {
      const parts = refs[0].split(":");
      const filePath = parts[0];
      const lineNum = parts[1];
      lines.push(`# Used in: ${path.relative(root, filePath)}:${lineNum}`);
      rows.push({ key, file: path.relative(root, filePath), line: lineNum, usages: String(refs.length) });
    }
    lines.push(`${key}=`);
    added.push(key);
  }
  for (const v of existingExample) {
    if (usedKeys.has(v.key)) continue;
    if (v.comment) lines.push(`# ${v.comment}`);
    lines.push(`# UNUSED: ${v.key}=`);
  }
  if (added.length === 0 && existingExample.length === 0) {
    log.warn("No variables found to write.");
    return { ok: false };
  }
  if (fs.existsSync(outPath)) {
    log.warn(`${opts.out} already exists — refusing to overwrite.`);
    return { ok: false };
  }
  safeWriteFile(outPath, lines.join("\n") + "\n");
  log.success(`Created ${opts.out} with ${added.length} usage-derived key(s).`);
  if (rows.length > 0) {
    console.log("");
    console.log(renderSection("Generated variables"));
    console.log(renderTable(
      [
        { key: "key", header: "Variable", width: 24, align: "left" },
        { key: "file", header: "File", width: 34, align: "left" },
        { key: "line", header: "Line", width: 6, align: "right" },
        { key: "usages", header: "Usages", width: 8, align: "right" },
      ],
      rows,
    ));
    console.log("");
  }
  console.log(renderInfo("Fill in real values in " + opts.out + ", then run: environmentsentrry check"));
  console.log("");
  return { ok: true };
}
