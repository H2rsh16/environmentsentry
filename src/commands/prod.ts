import * as fs from "fs";
import * as path from "path";
import pc from "picocolors";
import { detectEnvFiles } from "../core/detector";
import { parseEnv } from "../core/parser";
import { validate } from "../core/validator";
import { execa } from "execa";
import {
  renderHeader,
  renderSection,
  renderSuccess,
  renderError,
  renderWarn,
  renderInfo,
} from "../utils/table";
import { log } from "../utils/logger";

interface ProdOptions { root: string; force: boolean; }

export async function runProd(opts: ProdOptions): Promise<{ ok: boolean }> {
  const root = path.resolve(opts.root);
  const detected = detectEnvFiles(root, ".env", ".env.example");
  if (!detected.exampleExists) {
    console.log(renderError("Cannot create production env: .env.example not found."));
    console.log(renderInfo("Create a .env.example listing the variables your app needs."));
    return { ok: false };
  }

  const expected = parseEnv(detected.examplePath).vars;
  const actual = detected.envExists ? parseEnv(detected.envPath).vars : [];
  const result = validate(detected.envPath, expected, actual);

  if (!result.ok) {
    console.log(renderError("Validation failed. Fix issues before creating production env."));
    for (const issue of result.issues) {
      console.log(`  [${issue.status}] ${pc.bold(issue.key)} ${pc.dim(issue.reason || "")}`);
    }
    if (!opts.force) return { ok: false };
  }

  const prodPath = path.join(root, ".env.production");
  if (fs.existsSync(prodPath) && !opts.force) {
    console.log(renderError(`${prodPath} already exists. Use --force to overwrite.`));
    return { ok: false };
  }

  const lines: string[] = [];
  lines.push("# Production environment — generated by environmentsentrry");
  lines.push("# Fill in real production values before deploying. Never commit this file.");
  lines.push("");
  for (const v of expected) {
    if (v.comment) lines.push(`# ${v.comment}`);
    lines.push(`${v.key}=`);
  }
  fs.writeFileSync(prodPath, lines.join("\n") + "\n", { mode: 0o600 });

  console.log(renderHeader("environmentsentrry prod", "Production environment setup"));
  console.log(renderSuccess(`Created ${prodPath} with ${expected.length} key(s).`));
  console.log("");

  let testOk = true;
  try {
    await execa("npm", ["test"], { cwd: root, stdio: "inherit" });
  } catch {
    testOk = false;
    console.log(renderError("Tests failed."));
  }

  if (testOk) {
    console.log(renderSuccess("Production env created and tests passed."));
  } else {
    console.log(renderWarn("Production env created but tests failed. Review before deploying."));
  }
  console.log("");
  return { ok: testOk };
}
